import type { Doc, Feature, PlaneId, Selection } from '../types';
import { newId, uniqueName } from './doc';
import { regenerate } from './regenerate';
import type { SolidSpec } from '../geometry/solid';

export type CommandId = 'newSketch' | 'extrude' | 'fillet' | 'shell' | 'move';

export type CommandState = {
  id: CommandId;
  inputs: Record<string, string>;
  editingFeatureId?: string;
};

export type CommandField =
  | {
      key: string;
      label: string;
      type: 'select';
      options: { value: string; label: string }[];
      hint?: string;
    }
  | { key: string; label: string; type: 'text'; unit?: string; hint?: string }
  | { key: string; label: string; type: 'note'; text: string };

export const COMMAND_LABEL: Record<CommandId, string> = {
  newSketch: 'New Sketch',
  extrude: 'Extrude',
  fillet: 'Fillet',
  shell: 'Shell',
  move: 'Move / Copy',
};

export function featureInputs(feature: Feature): Record<string, string> {
  if (feature.kind === 'extrude') {
    return { sketchId: feature.sketchId, distance: feature.distance };
  }
  if (feature.kind === 'fillet') {
    return { bodyId: feature.bodyId, radius: feature.radius };
  }
  if (feature.kind === 'shell') {
    return { bodyId: feature.bodyId, thickness: feature.thickness };
  }
  return { bodyId: feature.bodyId, x: feature.offset.x, y: feature.offset.y, z: feature.offset.z };
}

function componentForNewSketch(doc: Doc, selection: Selection[]): string {
  const bodyId = selection.find((s) => s.kind === 'body')?.id;
  const body = bodyId ? doc.bodies.find((b) => b.id === bodyId) : undefined;
  if (body) return body.componentId;
  const child = doc.components.find((c) => c.parentId !== null);
  return child ? child.id : doc.components[0].id;
}

export function commandDefaults(doc: Doc, selection: Selection[], id: CommandId): Record<string, string> {
  const selectedBody = selection.find((s) => s.kind === 'body')?.id ?? '';
  const selectedSketch = selection.find((s) => s.kind === 'sketch')?.id ?? '';
  const selectedPlane = selection.find((s) => s.kind === 'plane')?.id ?? 'XY';

  if (id === 'newSketch') return { plane: selectedPlane };
  if (id === 'extrude') {
    return {
      sketchId: selectedSketch || doc.sketches[doc.sketches.length - 1]?.id || '',
      distance: '10',
    };
  }
  if (id === 'fillet') return { bodyId: selectedBody, radius: '3' };
  if (id === 'shell') return { bodyId: selectedBody, thickness: '2' };
  return { bodyId: selectedBody, x: '0', y: '0', z: '10' };
}

